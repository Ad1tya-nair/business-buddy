import os
import smtplib
from email.message import EmailMessage

from dotenv import load_dotenv


load_dotenv()


def send_action_item_email(
    task: str,
    owner_name: str,
    owner_email: str,
    due_date: str | None,
    meeting_name: str,
) -> bool:

    print("\n========== EMAIL DEBUG ==========")
    print(f"Task: {task}")
    print(f"Owner: {owner_name}")
    print(f"Recipient: {owner_email}")
    print(f"Due date: {due_date}")
    print(f"Meeting: {meeting_name}")

    host = os.getenv("SMTP_HOST")
    port = os.getenv("SMTP_PORT", "587")
    username = os.getenv("SMTP_USER")
    password = os.getenv("SMTP_PASSWORD")
    sender = os.getenv("SMTP_FROM") or username

    print(f"SMTP_HOST: {host}")
    print(f"SMTP_PORT: {port}")
    print(f"SMTP_USER: {username}")
    print(f"SMTP_FROM: {sender}")
    print(
        f"SMTP_PASSWORD: "
        f"{'SET' if password else 'NOT SET'}"
    )

    if not owner_email:
        print("EMAIL RESULT: FAILED")
        print("Reason: No owner email was provided.")
        print("================================\n")
        return False

    if not host:
        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP_HOST is not configured.")
        print("================================\n")
        return False

    if not username:
        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP_USER is not configured.")
        print("================================\n")
        return False

    if not password:
        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP_PASSWORD is not configured.")
        print("================================\n")
        return False

    if not sender:
        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP_FROM is not configured.")
        print("================================\n")
        return False

    try:
        port = int(port)
    except ValueError:
        print("EMAIL RESULT: FAILED")
        print(f"Reason: Invalid SMTP_PORT: {port}")
        print("================================\n")
        return False

    message = EmailMessage()

    message["Subject"] = f"Meeting action item: {task}"
    message["From"] = sender
    message["To"] = owner_email

    message.set_content(
        f"Hello {owner_name or 'there'},\n\n"
        f"An action item from the meeting "
        f"'{meeting_name}' has been confirmed.\n\n"
        f"Task: {task}\n"
        f"Due date: {due_date or 'Not specified'}\n\n"
        "This notification was generated by "
        "AI Meeting Intelligence Companion."
    )

    try:
        print("Connecting to SMTP server...")

        with smtplib.SMTP(
            host,
            port,
            timeout=15,
        ) as server:

            print("SMTP connection established.")

            server.ehlo()

            print("Starting TLS...")

            server.starttls()

            server.ehlo()

            print("TLS established.")

            print("Authenticating SMTP account...")

            server.login(
                username,
                password,
            )

            print("SMTP authentication successful.")

            print(
                f"Sending email to {owner_email}..."
            )

            server.send_message(message)

        print("EMAIL RESULT: SUCCESS")
        print("================================\n")

        return True

    except smtplib.SMTPAuthenticationError as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP authentication failed.")
        print(f"SMTP error: {exc}")
        print("================================\n")

        return False

    except smtplib.SMTPConnectError as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: Could not connect to SMTP server.")
        print(f"SMTP error: {exc}")
        print("================================\n")

        return False

    except smtplib.SMTPServerDisconnected as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP server disconnected.")
        print(f"SMTP error: {exc}")
        print("================================\n")

        return False

    except smtplib.SMTPException as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: SMTP error.")
        print(f"SMTP error: {exc}")
        print("================================\n")

        return False

    except OSError as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: Network/OS error.")
        print(f"OS error: {exc}")
        print("================================\n")

        return False

    except Exception as exc:

        print("EMAIL RESULT: FAILED")
        print("Reason: Unexpected error.")
        print(f"Error: {exc}")
        print("================================\n")

        return False